// Run with the local Vite dev server. All financial writes use an in-memory fixture.
import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { browser } from './chromium.mjs'
const b = await browser()
const q = JSON.stringify
const row = '[data-category-id="food"]'
const input = '#assign-food'
const edit = `${row} .assigned-value`
const save = `${row} .save-amount`
const pressEnter = async () => {
  await b.evaluate(`document.querySelector(${q(input)}).focus()`)
  await b.command('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' })
  await b.command('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
}
const drag = async target => b.evaluate(`(async()=>{const source=document.querySelector('${row} .category-name');const target=document.querySelector(${q(target)});const dataTransfer=new DataTransfer();source.dispatchEvent(new DragEvent('dragstart',{bubbles:true,cancelable:true,dataTransfer}));target.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer}));await Promise.resolve();if(!target.closest('tbody').classList.contains('drop-target'))throw Error('Missing drop highlight');target.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer}));source.dispatchEvent(new DragEvent('dragend',{bubbles:true,dataTransfer}));})()`)
try {
  await b.command('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await b.evaluate(`import('/test/browser/budget-table-harness.ts').then(m=>{window.fixture=m.mountBudgetTable();return true})`)
  await b.waitFor(`Boolean(document.querySelector(${q(edit)}))`)
  assert.deepEqual(await b.evaluate(`Array.from(document.querySelectorAll('thead th')).map(e=>e.textContent.trim())`), ['Categoría', 'Asignado CLP · editable', 'Usado CLP', 'Disponible CLP', 'Detalles'])
  assert.equal(await b.evaluate(`document.querySelectorAll('.assignment-form').length`), 0)
  await b.click(edit)
  assert.equal(await b.evaluate(`document.activeElement.id`), 'assign-food')
  assert.equal(await b.evaluate(`document.querySelector(${q(save)}).textContent.trim()`), '')
  assert.equal(await b.evaluate(`document.querySelector(${q(save)}).getAttribute('aria-label')`), 'Guardar asignación de Comida')
  await b.set(input, '75.125')
  await pressEnter()
  await b.waitFor(`Boolean(document.querySelector(${q(edit)}))`)
  assert.equal(await b.evaluate(`window.fixture.writes.at(-1).body.amount`), '75.125')
  assert.equal(await b.evaluate(`document.activeElement.classList.contains('assigned-value')`), true)
  await b.click(edit)
  await b.set(input, '90.0001')
  await b.click(save)
  await b.waitFor(`Boolean(document.querySelector(${q(edit)}))`)
  assert.equal(await b.evaluate(`window.fixture.writes.at(-1).body.amount`), '90.0001')
  await b.click(edit)
  await b.set(input, 'bad')
  await pressEnter()
  assert.equal(await b.evaluate(`window.fixture.writes.length`), 2)
  await b.set(input, '95')
  await b.evaluate(`window.fixture.rejectWrite.value=true`)
  await b.click(save)
  await b.waitFor(`window.fixture.assignments.saving.value===null`)
  assert.equal(await b.evaluate(`document.querySelector(${q(input)}).value`), '95')
  await b.evaluate(`window.fixture.rejectWrite.value=false;window.fixture.budget.value={...window.fixture.budget.value,revision:'99'}`)
  await b.waitFor(`document.querySelector(${q(save)}).disabled`)
  const beforeStale = await b.evaluate(`window.fixture.writes.length`)
  await pressEnter()
  assert.equal(await b.evaluate(`window.fixture.writes.length`), beforeStale)
  await b.evaluate(`Array.from(document.querySelectorAll('button')).find(e=>e.textContent.includes('Revisé los valores')).click()`)
  await pressEnter()
  await b.waitFor(`Boolean(document.querySelector(${q(edit)}))`)
  // Native mouse movement exercises the browser's draggable source behavior.
  const points = await b.evaluate(`(()=>{const a=document.querySelector('${row} .category-name').getBoundingClientRect();const z=document.querySelector('[data-group-id="empty"] .group-heading').getBoundingClientRect();return {x:a.x+20,y:a.y+a.height/2,tx:z.x+100,ty:z.y+z.height/2}})()`)
  await b.command('Input.dispatchMouseEvent', { type: 'mouseMoved', x: points.x, y: points.y })
  await b.command('Input.dispatchMouseEvent', { type: 'mousePressed', x: points.x, y: points.y, button: 'left', clickCount: 1 })
  for (let step = 1; step <= 10; step++) await b.command('Input.dispatchMouseEvent', { type: 'mouseMoved', x: points.x + (points.tx - points.x) * step / 10, y: points.y + (points.ty - points.y) * step / 10, button: 'left', buttons: 1 })
  await b.command('Input.dispatchMouseEvent', { type: 'mouseMoved', x: points.tx + 1, y: points.ty + 1, button: 'left', buttons: 1 })
  await b.command('Input.dispatchMouseEvent', { type: 'mouseMoved', x: points.tx, y: points.ty, button: 'left', buttons: 1 })
  await b.command('Input.dispatchMouseEvent', { type: 'mouseReleased', x: points.tx, y: points.ty, button: 'left', clickCount: 1 })
  await b.waitFor(`document.querySelector('[data-group-id="empty"] ${row}')!==null`)
  await drag('[data-category-id="rent"]')
  await b.waitFor(`document.querySelector('[data-group-id="general"] ${row}')!==null`)
  await drag('[data-group-id="empty"] .group-heading')
  await b.waitFor(`document.querySelector('[data-group-id="empty"] ${row}')!==null`)
  assert.equal(await b.evaluate(`window.fixture.writes.at(-1).body.group_id`), 'empty')
  await drag('[data-category-id="rent"]')
  await b.waitFor(`document.querySelector('[data-group-id="general"] ${row}')!==null`)
  await b.evaluate(`window.fixture.pendingRoutes.value=['/api/categories/food']`)
  await b.waitFor(`document.querySelector('${row} .category-name').draggable===false`)
  await b.evaluate(`window.fixture.pendingRoutes.value=[];window.fixture.budget.value.closed=true`)
  await b.click(edit)
  assert.equal(await b.evaluate(`document.querySelector('${row} textarea').required`), true)
  await b.set(input, '100')
  const beforeReason = await b.evaluate(`window.fixture.writes.length`)
  await pressEnter()
  assert.equal(await b.evaluate(`window.fixture.writes.length`), beforeReason)
  await b.set(`${row} textarea`, 'Reviewed correction')
  await b.click(save)
  await b.waitFor(`Boolean(document.querySelector(${q(edit)}))`)
  assert.equal(await b.evaluate(`window.fixture.writes.at(-1).body.reason`), 'Reviewed correction')
  await writeFile('/tmp/lukas-budget-table.png', Buffer.from((await b.command('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await b.command('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false })
  assert.equal(await b.evaluate(`document.documentElement.scrollWidth<=innerWidth`), true)
  console.log('PASS: clear headers; click-to-edit focus; icon and Enter saves; exact decimals; validation and failed/stale drafts; category drops on empty groups and rows; pending locks; closed correction reason; mobile overflow.')
} finally { await b.close() }
